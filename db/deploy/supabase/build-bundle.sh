#!/usr/bin/env bash
# Menggabung migrasi kanonik + seed menjadi satu file untuk SQL Editor Supabase.
# File hasil (01_schema_and_seed.sql) adalah artefak turunan: jangan diedit tangan.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; DB="$HERE/../.."
OUT="$HERE/01_schema_and_seed.sql"
{
  echo "-- GENERATED by build-bundle.sh dari db/migrations/*.sql + db/seed/*.sql. Jangan diedit."
  for f in "$DB"/migrations/*.sql "$DB"/seed/*.sql; do
    echo; echo "-- ===== $(basename "$f") ====="; cat "$f"
  done
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
